// OpenNR -- a ReShade add-on that runs a small image-enhancement network on the game's frame.
//
// A frame, in order:
//   1. stage      the frame, sampled down to the network's resolution, into 16 input channels
//   2. network    19 convolutions (opennr_model.hpp), on the game's GPU or on another one
//   3. composite  the network's correction lifted back to the output resolution and added to
//                 the full-resolution frame, with Strength, the style's grade, Detail and
//                 Colour strength, Compare, and the view
//
// On an HDR swap chain (scRGB or HDR10) the network is shown the frame over a white point, as an
// SDR picture, and its correction goes back to the frame in linear light.
//
// When it can, the add-on does this before the game draws its HUD, so the HUD is drawn over the
// corrected picture instead of being corrected with it. D3D11 and D3D12; Vulkan is experimental.
//
// Copyright (c) 2026 MakeDecisionWorth. MIT licence, see LICENSE.

